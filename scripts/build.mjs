// Builds every distributable from icons/*.json. `npm run build`
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, bitmapToNodes, config, readIcon, toCamel, toPascal } from './lib.mjs';
import { lintAll } from './lint.mjs';

const HEADER = '// Auto-generated by scripts/build.mjs — do not edit.\n';
const ICONS_PKG = join(ROOT, 'packages/icons');
const REACT_PKG = join(ROOT, 'packages/react');
const SITE_DIR = join(ROOT, 'site');
const G = config.grid;

const write = (file, content) => {
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, content);
};
const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const attrString = (attrs) =>
  Object.entries(attrs)
    .map(([k, v]) => `${k}="${esc(v)}"`)
    .join(' ');

const ROOT_ATTRS = { fill: 'currentColor', 'shape-rendering': 'crispEdges' };

/** Children markup for static outputs (svg files, sprite, iconify). */
const childrenMarkup = (nodes) => nodes.map(([tag, attrs]) => `<${tag} ${attrString(attrs)}/>`).join('');

// ---------------------------------------------------------------------------
console.time('build');
const { errorCount, names } = lintAll({ quiet: true });
if (errorCount) {
  console.error(`✖ lint failed with ${errorCount} errors — run \`npm run lint\` for details`);
  process.exit(1);
}

const icons = names.map((name) => {
  const { data } = readIcon(name);
  const nodes = bitmapToNodes(data.pixels);
  return {
    name,
    pascal: toPascal(name),
    camel: toCamel(name),
    pixels: data.pixels,
    nodes,
    tags: data.tags,
    categories: data.categories,
    aliases: data.aliases || [],
  };
});
const version = JSON.parse(readFileSync(join(ICONS_PKG, 'package.json'), 'utf8')).version;
const nameUnion = (list) => list.map((n) => `'${n}'`).join(' | ');
const allNames = icons.flatMap((i) => [i.name, ...i.aliases]).sort();

// ---------------------------------------------------------------------------
// @ottomind-ai/icons
// ---------------------------------------------------------------------------
const iconsDist = join(ICONS_PKG, 'dist');
rmSync(iconsDist, { recursive: true, force: true });
mkdirSync(iconsDist, { recursive: true });
copyFileSync(join(ICONS_PKG, 'src/to-svg.js'), join(iconsDist, 'to-svg.js'));

let iconsIndex = `${HEADER}export { toSvg } from './to-svg.js';\n\n`;
let iconsDts = `${HEADER}${readFileSync(join(ICONS_PKG, 'src/types.d.ts'), 'utf8')}\n/** Every icon name, aliases included. */\nexport type IconName = ${nameUnion(allNames)};\n\n`;
for (const icon of icons) {
  iconsIndex += `/** ${icon.name} — ${icon.tags.join(', ')} */\nexport const ${icon.camel} = ${JSON.stringify(icon.nodes)};\n`;
  iconsDts += `/** ${icon.name} */\nexport declare const ${icon.camel}: IconNode;\n`;
  for (const alias of icon.aliases) {
    iconsIndex += `/** @deprecated renamed to ${icon.name} */\nexport { ${icon.camel} as ${toCamel(alias)} };\n`;
    iconsDts += `/** @deprecated renamed to ${icon.name} */\nexport declare const ${toCamel(alias)}: IconNode;\n`;
  }
}
write(join(iconsDist, 'index.js'), iconsIndex);
write(join(iconsDist, 'index.d.ts'), iconsDts);

// standalone SVG files
for (const icon of icons) {
  write(
    join(iconsDist, 'svg', `${icon.name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="${G}" height="${G}" viewBox="0 0 ${G} ${G}" ${attrString(ROOT_ATTRS)}>${childrenMarkup(icon.nodes)}</svg>\n`,
  );
}

// sprite
const symbols = icons
  .map(
    (icon) =>
      `<symbol id="${config.spritePrefix}${icon.name}" viewBox="0 0 ${G} ${G}" ${attrString(ROOT_ATTRS)}>${childrenMarkup(icon.nodes)}</symbol>`,
  )
  .join('\n');
write(join(iconsDist, 'sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols}\n</svg>\n`);

// Iconify JSON (submit to iconify/icon-sets, or load with addCollection())
const iconify = {
  prefix: config.iconifyPrefix,
  info: {
    name: 'ottomind icons',
    total: icons.length,
    version,
    author: { name: 'ottomind', url: 'https://ottomind.ai' },
    license: { title: 'MIT', spdx: 'MIT', url: 'https://github.com/ottomind-ai/icons/blob/main/LICENSE' },
    height: G,
    category: 'General',
    palette: false,
  },
  icons: Object.fromEntries(
    icons.map((icon) => [icon.name, { body: `<g ${attrString(ROOT_ATTRS)}>${childrenMarkup(icon.nodes)}</g>` }]),
  ),
  aliases: Object.fromEntries(icons.flatMap((icon) => icon.aliases.map((alias) => [alias, { parent: icon.name }]))),
  categories: Object.fromEntries(
    config.categories
      .map((cat) => [cat, icons.filter((i) => i.categories[0] === cat).map((i) => i.name)])
      .filter(([, list]) => list.length),
  ),
  width: G,
  height: G,
};
write(join(iconsDist, 'iconify.json'), `${JSON.stringify(iconify, null, 2)}\n`);

// metadata (docs sites, search, editors, AI tooling) — includes the source pixels
const metadata = {
  version,
  grid: G,
  count: icons.length,
  icons: Object.fromEntries(
    icons.map((i) => [
      i.name,
      { tags: i.tags, categories: i.categories, aliases: i.aliases, pixels: i.pixels },
    ]),
  ),
};
write(join(iconsDist, 'metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`);

// ---------------------------------------------------------------------------
// @ottomind-ai/icons-react
// ---------------------------------------------------------------------------
const reactDist = join(REACT_PKG, 'dist');
rmSync(reactDist, { recursive: true, force: true });
mkdirSync(join(reactDist, 'icons'), { recursive: true });
copyFileSync(join(REACT_PKG, 'src/create-icon.js'), join(reactDist, 'create-icon.js'));
copyFileSync(join(REACT_PKG, 'src/types.d.ts'), join(reactDist, 'types.d.ts'));

let reactIndex = `${HEADER}export { createIcon } from './create-icon.js';\n`;
let reactDts = `${HEADER}export * from './types';\n/** Every icon name, aliases included. */\nexport type IconName = ${nameUnion(allNames)};\n`;
for (const icon of icons) {
  write(
    join(reactDist, 'icons', `${icon.name}.js`),
    `${HEADER}import { createIcon } from '../create-icon.js';\n\n` +
      `const ${icon.pascal} = /*#__PURE__*/ createIcon('${icon.name}', '${icon.pascal}', ${JSON.stringify(icon.nodes)});\n\n` +
      `export default ${icon.pascal};\nexport { ${icon.pascal}, ${icon.pascal} as ${icon.pascal}Icon };\n`,
  );
  write(
    join(reactDist, 'icons', `${icon.name}.d.ts`),
    `${HEADER}import type { OttomindIcon } from '../types';\n\n` +
      `/** ${icon.name} — ${icon.tags.join(', ')} */\ndeclare const ${icon.pascal}: OttomindIcon;\n` +
      `export default ${icon.pascal};\nexport { ${icon.pascal}, ${icon.pascal} as ${icon.pascal}Icon };\n`,
  );
  const exportNames = [icon.pascal, ...icon.aliases.map(toPascal)].flatMap((n) => [n, `${n}Icon`]);
  const list = exportNames.map((n) => `default as ${n}`).join(', ');
  reactIndex += `export { ${list} } from './icons/${icon.name}.js';\n`;
  reactDts += `export { ${list} } from './icons/${icon.name}';\n`;
}
write(join(reactDist, 'index.js'), reactIndex);
write(join(reactDist, 'index.d.ts'), reactDts);

// ---------------------------------------------------------------------------
// Docs / preview site (static, deployable to icons.ottomind.ai)
// ---------------------------------------------------------------------------
const siteData = {
  version,
  grid: G,
  padding: config.padding,
  categories: config.categories,
  categoriesTr: config.categoriesTr,
  icons: icons.map((i) => ({
    name: i.name,
    pascal: i.pascal,
    tags: i.tags,
    categories: i.categories,
    aliases: i.aliases,
    pixels: i.pixels,
    nodes: i.nodes,
  })),
};
// Site assets: ottomind pixel font (inlined, so the page is one file) and the site mark.
const ASSETS = join(SITE_DIR, 'assets');
const pixelFont = readFileSync(join(ASSETS, 'ottomind-pixel.woff2')).toString('base64');
const favicon = readFileSync(join(ASSETS, 'favicon.svg'), 'utf8').trim();
const mark = JSON.parse(readFileSync(join(ASSETS, 'mark.json'), 'utf8'));
const template = readFileSync(join(SITE_DIR, 'template.html'), 'utf8');
write(
  join(SITE_DIR, 'dist/index.html'),
  template
    .replace('/*__ICON_DATA__*/null', () => JSON.stringify(siteData).replace(/</g, '\\u003c'))
    .replace('__PIXEL_FONT__', () => pixelFont)
    .replace('__FAVICON__', () => encodeURIComponent(favicon))
    .replace('__MARK_CHERRY__', () => mark.cherry)
    .replace('__MARK_MAIN__', () => mark.main),
);
copyFileSync(join(ASSETS, 'favicon.svg'), join(SITE_DIR, 'dist/favicon.svg'));
copyFileSync(join(iconsDist, 'sprite.svg'), join(SITE_DIR, 'dist/sprite.svg'));
copyFileSync(join(iconsDist, 'iconify.json'), join(SITE_DIR, 'dist/iconify.json'));

console.log(`✔ built ${icons.length} icons (v${version})`);
console.timeEnd('build');
